#!/usr/bin/env node
// Renders the website's example images once, with the user's own Replicate
// token, and records exactly what was sent. Already-rendered entries are
// skipped, so re-running costs nothing unless an entry is new or --force is given.
//
//   REPLICATE_API_TOKEN=... node scripts/render-examples.mjs [--only id,id] [--force] [--dry-run]
//
// Output: docs/assets/images/<id>.webp, docs/assets/images/manifest.json
// The token is read from the environment and never written or logged.
import { readFileSync, writeFileSync, existsSync, mkdirSync, unlinkSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as J from '../docs/assets/js/jai.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'docs', 'assets', 'images');
mkdirSync(outDir, { recursive: true });
const manifestPath = join(outDir, 'manifest.json');
const manifest = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, 'utf8')) : { note: 'Generated by scripts/render-examples.mjs. Do not edit by hand.', images: {} };
const showcase = JSON.parse(readFileSync(join(root, 'examples', 'showcase.json'), 'utf8'));
const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1].split(',') : null;
const force = args.includes('--force'), dry = args.includes('--dry-run');
const token = process.env.REPLICATE_API_TOKEN;
if (!token && !dry) { console.error('REPLICATE_API_TOKEN is not set'); process.exit(1); }

// The reference renderer's mapping (mirrors jai-tools/src/renderers/replicate).
const MODELS = {
  'black-forest-labs/flux-schnell': { aspects: ['1:1', '16:9', '21:9', '3:2', '2:3', '4:5', '5:4', '3:4', '4:3', '9:16', '9:21'], negative: false, image: false },
  'black-forest-labs/flux-dev': { aspects: ['1:1', '16:9', '21:9', '3:2', '2:3', '4:5', '5:4', '3:4', '4:3', '9:16', '9:21'], negative: false, image: true },
  'black-forest-labs/flux-kontext-pro': { aspects: ['1:1', '16:9', '9:16', '4:3', '3:4', '3:2', '2:3', '4:5', '5:4', '21:9', '9:21', '2:1', '1:2'], negative: false, image: true },
  'stability-ai/sdxl': { version: '7762fd07cf82c948538e41f63f77d685e02b063e37e496e96eefd46c929f9bdc', sizes: true, negative: true, image: true, shortWindow: true },
};

function nearestAspect(ratio, list) {
  let best = list[0], bd = Infinity;
  for (const a of list) { const [w, h] = a.split(':').map(Number); const d = Math.abs(Math.log((w / h) / ratio)); if (d < bd) { bd = d; best = a; } }
  return best;
}

function buildInput(entry, it, sourceDataURL) {
  const m = MODELS[entry.renderer];
  const style = it.style.join(', ');
  // Prompt assembly: description, then styles; short-window models get styles first.
  let prompt = it.description;
  if (style) prompt = m.shortWindow ? `${style}. ${prompt}` : `${prompt}\n\nStyle: ${style}.`;
  const input = { prompt };
  const ratio = it.aspect ? it.aspect.width / it.aspect.height : null;
  if (m.sizes) {
    const r = ratio || 1, px = 1024 * 1024;
    let w = Math.round(Math.sqrt(px * r) / 8) * 8, h = Math.round(Math.sqrt(px / r) / 8) * 8;
    Object.assign(input, { width: w, height: h, apply_watermark: false });
    if (it.avoid.length) input.negative_prompt = it.avoid.join(', ');
  } else if (ratio) input.aspect_ratio = nearestAspect(ratio, m.aspects);
  if (entry.renderer.includes('flux-schnell') || entry.renderer.includes('flux-dev')) Object.assign(input, { output_format: 'webp', output_quality: 85, num_outputs: 1 });
  if (entry.renderer.includes('kontext')) Object.assign(input, { input_image: sourceDataURL, aspect_ratio: 'match_input_image', output_format: 'png' });
  if (entry.seed !== undefined) input.seed = entry.seed;
  return input;
}

async function api(path, init = {}) {
  const res = await fetch('https://api.replicate.com/v1' + path, { ...init, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', ...(init.headers || {}) } });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(`${res.status} ${body.detail || body.title || JSON.stringify(body)}`);
  return body;
}

async function predict(model, input) {
  const m = MODELS[model];
  const path = m.version ? '/predictions' : `/models/${model}/predictions`;
  const payload = m.version ? { version: m.version, input } : { input };
  let p = await api(path, { method: 'POST', body: JSON.stringify(payload), headers: { Prefer: 'wait=60' } });
  for (let n = 0; !['succeeded', 'failed', 'canceled'].includes(p.status) && n < 120; n++) {
    await new Promise(r => setTimeout(r, 2000));
    p = await api(`/predictions/${p.id}`);
  }
  if (p.status !== 'succeeded') throw new Error(`prediction ${p.id} ${p.status}: ${p.error || ''}`);
  return p;
}

const toWebp = (src, dst) => execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', src, '-c:v', 'libwebp', '-quality', '82', dst]);
const tinyPreview = src => {
  const tmp = join(outDir, '.preview.webp');
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', src, '-vf', 'scale=8:8:force_original_aspect_ratio=decrease', '-c:v', 'libwebp', '-quality', '40', tmp]);
  const b = readFileSync(tmp); unlinkSync(tmp);
  return 'data:image/webp;base64,' + b.toString('base64');
};

for (const entry of showcase.entries) {
  if (only && !only.includes(entry.id)) continue;
  const file = join(outDir, entry.id + '.webp');
  if (existsSync(file) && manifest.images[entry.id] && !force) { console.log(`skip ${entry.id} (exists)`); continue; }
  const { document } = J.parse(entry.jai);
  const { interpreted: it } = J.interpret(document);
  let sourceDataURL = null;
  if (entry.source) {
    const s = join(outDir, entry.source + '.webp');
    if (!existsSync(s)) { if (dry) { console.log(`render ${entry.id}: needs ${entry.source} first`); continue; } throw new Error(`render ${entry.source} first`); }
    sourceDataURL = 'data:image/webp;base64,' + readFileSync(s).toString('base64');
  }
  const input = buildInput(entry, it, sourceDataURL);
  const shown = { ...input }; if (shown.input_image) shown.input_image = `(${entry.source}.webp, ${readFileSync(join(outDir, entry.source + '.webp')).length} bytes)`;
  console.log(`render ${entry.id} with ${entry.renderer}: ${JSON.stringify(shown)}`);
  if (dry) continue;
  const t0 = Date.now();
  const p = await predict(entry.renderer, input);
  const url = Array.isArray(p.output) ? p.output[0] : p.output;
  const bytes = Buffer.from(await (await fetch(url)).arrayBuffer());
  const tmp = join(outDir, '.download');
  writeFileSync(tmp, bytes);
  toWebp(tmp, file); unlinkSync(tmp);
  const dims = execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', file]).toString().trim().split(',').map(Number);
  manifest.images[entry.id] = {
    jai: entry.jai, canonical: J.serialize(document), identity: await J.identity(document),
    renderer: entry.renderer, version: p.version, prediction: p.id, created: p.created_at,
    seconds: Math.round((Date.now() - t0) / 100) / 10, width: dims[0], height: dims[1],
    sent: shown, preview: tinyPreview(file), source: entry.source || null,
  };
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 1) + '\n');
  console.log(`  -> ${entry.id}.webp ${dims.join('x')} in ${manifest.images[entry.id].seconds}s`);
}
